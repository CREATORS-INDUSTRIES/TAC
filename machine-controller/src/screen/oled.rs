//! SSD1306 128x64 por I2C-1, mismo bus que el ADS1115 (0x48).
//!
//! Pines Pi Zero 2W (BCM / fisico):
//!   3.3V   / 1          -> OLED VCC
//!   GND    / 6          -> OLED GND
//!   GPIO2  / 3   SDA1   -> OLED SDA
//!   GPIO3  / 5   SCL1   -> OLED SCL
//!
//! Dibujo en framebuffer local; nada llega a la pantalla hasta `flush`.
//!
//! Espejo respecto al eje horizontal por como va montado el modulo: INIT usa COM 0xC0, 0xC8 lo deja normal.

use rppal::i2c::I2c;

use crate::fader::Error;

pub const WIDTH: i32 = 128;
pub const HEIGHT: i32 = 64;
const PAGES: usize = HEIGHT as usize / 8;
// 0x3D si el modulo tiene el jumper de direccion cambiado
pub const ADDR: u16 = 0x3C;

const CTRL_CMD: u8 = 0x00;
const CTRL_DATA: u8 = 0x40;

const INIT: &[u8] = &[
    0xAE, // off
    0xD5, 0x80, // clock
    0xA8, (HEIGHT - 1) as u8, // multiplex
    0xD3, 0x00, // offset
    0x40, // start line 0
    0x8D, 0x14, // charge pump interno: sin el, pantalla negra con VCC 3.3V
    0x20, 0x00, // direccionamiento horizontal
    0xA1, // segment remap
    0xC0, // COM ascendente
    0xDA, if HEIGHT == 64 { 0x12 } else { 0x02 },
    0x81, 0xCF, // contraste
    0xD9, 0xF1, // precharge
    0xDB, 0x40, // VCOMH
    0xA4, // sigue la RAM
    0xA6, // no invertido
    0x2E, // scroll off
    0xAF, // on
];

pub struct Oled {
    i2c: I2c,
    buf: [u8; WIDTH as usize * PAGES],
}

impl Oled {
    pub fn new() -> Result<Self, Error> {
        Self::with_addr(ADDR)
    }

    pub fn with_addr(addr: u16) -> Result<Self, Error> {
        let mut i2c = I2c::with_bus(1)?;
        i2c.set_slave_address(addr)?;
        let mut o = Self { i2c, buf: [0; WIDTH as usize * PAGES] };
        o.cmd(INIT)?;
        o.flush()?;
        Ok(o)
    }

    fn cmd(&mut self, cmds: &[u8]) -> Result<(), Error> {
        let mut msg = Vec::with_capacity(cmds.len() + 1);
        msg.push(CTRL_CMD);
        msg.extend_from_slice(cmds);
        self.i2c.write(&msg)?;
        Ok(())
    }

    pub fn flush(&mut self) -> Result<(), Error> {
        self.cmd(&[0x21, 0, (WIDTH - 1) as u8, 0x22, 0, (PAGES - 1) as u8])?;
        let mut msg = [0u8; WIDTH as usize + 1];
        msg[0] = CTRL_DATA;
        for page in self.buf.chunks(WIDTH as usize) {
            msg[1..].copy_from_slice(page);
            self.i2c.write(&msg)?;
        }
        Ok(())
    }

    pub fn set_contrast(&mut self, v: u8) -> Result<(), Error> {
        self.cmd(&[0x81, v])
    }

    pub fn set_inverted(&mut self, on: bool) -> Result<(), Error> {
        self.cmd(&[if on { 0xA7 } else { 0xA6 }])
    }

    pub fn power(&mut self, on: bool) -> Result<(), Error> {
        self.cmd(&[if on { 0xAF } else { 0xAE }])
    }

    pub fn clear(&mut self) {
        self.buf.fill(0);
    }

    /// Fuera de pantalla se ignora: las figuras pueden salirse sin recortar a mano.
    pub fn pixel(&mut self, x: i32, y: i32, on: bool) {
        if !(0..WIDTH).contains(&x) || !(0..HEIGHT).contains(&y) {
            return;
        }
        let i = (y / 8 * WIDTH + x) as usize;
        let bit = 1 << (y % 8);
        if on { self.buf[i] |= bit } else { self.buf[i] &= !bit }
    }

    pub fn hline(&mut self, x: i32, y: i32, w: i32, on: bool) {
        for i in x..x + w {
            self.pixel(i, y, on);
        }
    }

    pub fn vline(&mut self, x: i32, y: i32, h: i32, on: bool) {
        for j in y..y + h {
            self.pixel(x, j, on);
        }
    }

    /// Bresenham.
    pub fn line(&mut self, mut x0: i32, mut y0: i32, x1: i32, y1: i32, on: bool) {
        let (dx, sx) = ((x1 - x0).abs(), if x0 < x1 { 1 } else { -1 });
        let (dy, sy) = (-(y1 - y0).abs(), if y0 < y1 { 1 } else { -1 });
        let mut err = dx + dy;
        loop {
            self.pixel(x0, y0, on);
            if x0 == x1 && y0 == y1 {
                break;
            }
            let e2 = 2 * err;
            if e2 >= dy {
                err += dy;
                x0 += sx;
            }
            if e2 <= dx {
                err += dx;
                y0 += sy;
            }
        }
    }

    pub fn rect(&mut self, x: i32, y: i32, w: i32, h: i32, on: bool) {
        self.hline(x, y, w, on);
        self.hline(x, y + h - 1, w, on);
        self.vline(x, y, h, on);
        self.vline(x + w - 1, y, h, on);
    }

    pub fn fill_rect(&mut self, x: i32, y: i32, w: i32, h: i32, on: bool) {
        for j in y..y + h {
            self.hline(x, j, w, on);
        }
    }

    pub fn circle(&mut self, cx: i32, cy: i32, r: i32, on: bool) {
        self.circle_with(r, |o, x, y| {
            for (px, py) in [(x, y), (y, x), (-y, x), (-x, y), (-x, -y), (-y, -x), (y, -x), (x, -y)] {
                o.pixel(cx + px, cy + py, on);
            }
        });
    }

    pub fn fill_circle(&mut self, cx: i32, cy: i32, r: i32, on: bool) {
        self.circle_with(r, |o, x, y| {
            o.hline(cx - x, cy + y, 2 * x + 1, on);
            o.hline(cx - x, cy - y, 2 * x + 1, on);
            o.hline(cx - y, cy + x, 2 * y + 1, on);
            o.hline(cx - y, cy - x, 2 * y + 1, on);
        });
    }

    /// Punto medio: `plot` recibe cada (x, y) del primer octante.
    fn circle_with(&mut self, r: i32, mut plot: impl FnMut(&mut Self, i32, i32)) {
        let (mut x, mut y, mut d) = (r, 0, 1 - r);
        while x >= y {
            plot(self, x, y);
            y += 1;
            if d < 0 {
                d += 2 * y + 1;
            } else {
                x -= 1;
                d += 2 * (y - x) + 1;
            }
        }
    }

    /// Fuente 5x7 en celda 6x8, escalada por `scale`. Devuelve la x tras el ultimo caracter.
    pub fn text(&mut self, x: i32, y: i32, s: &str, scale: i32, on: bool) -> i32 {
        let mut cx = x;
        for c in s.chars() {
            let glyph = match c {
                ' '..='~' => &FONT[(c as usize - 0x20) * 5..][..5],
                _ => &FONT[('?' as usize - 0x20) * 5..][..5],
            };
            for (col, bits) in glyph.iter().enumerate() {
                for row in 0..7 {
                    if bits >> row & 1 == 1 {
                        self.fill_rect(cx + col as i32 * scale, y + row * scale, scale, scale, on);
                    }
                }
            }
            cx += 6 * scale;
        }
        cx
    }

    pub fn text_width(s: &str, scale: i32) -> i32 {
        s.chars().count() as i32 * 6 * scale - scale
    }
}

